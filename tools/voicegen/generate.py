"""Render every English phrase in every reference voice with Chatterbox.

  .venv/bin/python generate.py            # all phrases
  .venv/bin/python generate.py --phrases 4  # first 4 phrases only (quick test)

Resumable: clips that already exist are skipped. Writes AAC (.m4a) clips to
audio/chatterbox/<tag>/ and a manifest the game loads as a plain <script>
(so it also works when index.html is opened straight from disk).
"""
import argparse
import glob
import json
import os
import re
import subprocess
import tempfile

import torch
import torchaudio
from chatterbox.tts import ChatterboxTTS

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
REFS = os.path.join(HERE, "refs")
OUT = os.path.join(ROOT, "audio", "chatterbox")


def read_phrases():
    """EN_PHRASES straight out of index.html, so the two never drift apart."""
    html = open(os.path.join(ROOT, "index.html"), encoding="utf-8").read()
    block = re.search(r"var EN_PHRASES = \[(.*?)\];", html, re.S).group(1)
    return re.findall(r'"((?:[^"\\]|\\.)*)"', block)


def write_manifest():
    clips = {}
    for path in sorted(glob.glob(os.path.join(OUT, "*", "*.m4a"))):
        tag = os.path.basename(os.path.dirname(path))
        clips.setdefault(tag, []).append({
            "src": os.path.relpath(path, ROOT).replace(os.sep, "/"),
            "phrase": int(re.search(r"-p(\d+)\.m4a$", path).group(1)),
        })
    with open(os.path.join(OUT, "manifest.js"), "w") as fh:
        fh.write("/* Generated by tools/voicegen/generate.py. */\n")
        fh.write("window.CLIP_PACKS = window.CLIP_PACKS || {};\n")
        fh.write("window.CLIP_PACKS.chatterbox = " + json.dumps(clips, indent=1) + ";\n")
    print("manifest:", sum(len(v) for v in clips.values()), "clips,", len(clips), "accents")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--phrases", type=int, default=0, help="only the first N phrases")
    ap.add_argument("--only", default="", help="comma-separated accent tags")
    args = ap.parse_args()

    phrases = read_phrases()
    if args.phrases:
        phrases = phrases[: args.phrases]
    refs = sorted(glob.glob(os.path.join(REFS, "*.wav")))
    if args.only:
        keep = set(args.only.split(","))
        refs = [r for r in refs if os.path.basename(r).rsplit("-", 1)[0] in keep]

    device = "mps" if torch.backends.mps.is_available() else "cpu"
    model = ChatterboxTTS.from_pretrained(device=device)

    for ref in refs:
        name = os.path.basename(ref)[:-4]          # en-IE-1
        tag, voice = name.rsplit("-", 1)
        os.makedirs(os.path.join(OUT, tag), exist_ok=True)
        model.prepare_conditionals(ref, exaggeration=0.5)
        for i, text in enumerate(phrases):
            dest = os.path.join(OUT, tag, f"v{voice}-p{i}.m4a")
            if os.path.exists(dest):
                continue
            # cfg_weight carries the reference's accent; keep it at the default rather than lowering it.
            wav = model.generate(text, exaggeration=0.5, cfg_weight=0.5)
            with tempfile.NamedTemporaryFile(suffix=".wav") as tmp:
                torchaudio.save(tmp.name, wav.cpu(), model.sr)
                # afconvert very occasionally crashes on a file it handles fine the second time.
                for attempt in range(3):
                    done = subprocess.run(["afconvert", "-f", "m4af", "-d", "aac", "-b", "64000", tmp.name, dest])
                    if done.returncode == 0:
                        break
                    if os.path.exists(dest):
                        os.remove(dest)
                else:
                    print("could not encode", name, i, flush=True)
                    continue
            print(name, i, text, flush=True)
        write_manifest()


if __name__ == "__main__":
    main()
